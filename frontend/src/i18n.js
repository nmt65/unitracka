export function t(value, language = "ro") {
  if (!value) return value;
  if (language !== "en") return value;
  return en[value] || value;
}

export function nt(value, language = "ro") {
  if (!value) return value;
  if (language === "ro") return ro[value] || value;
  return en[value] || value;
}

function translateValue(value, language) {
  if (!value) return value;
  const dictionary = language === "en" ? en : ro;
  const trimmed = value.trim();
  const translated = dictionary[trimmed];
  if (translated) return value.replace(trimmed, translated);
  const replacements = language === "en" ? inlineEn : inlineRo;
  let nextValue = value;
  replacements.forEach(([source, target]) => {
    const escaped = source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const wordCharacter = /[\p{L}\p{N}]/u;
    const prefix = wordCharacter.test(source[0]) ? "(?<![\\p{L}\\p{N}])" : "";
    const suffix = wordCharacter.test(source[source.length - 1]) ? "(?![\\p{L}\\p{N}])" : "";
    nextValue = nextValue.replace(new RegExp(`${prefix}${escaped}${suffix}`, "gu"), target);
  });
  return nextValue;
}

function translateTree(root, language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      const parent = node.parentElement;
      if (!parent || ["SCRIPT", "STYLE", "TEXTAREA"].includes(parent.tagName)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes = [];
  while (walker.nextNode() && nodes.length < 1200) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    const nextValue = translateValue(node.nodeValue, language);
    if (nextValue !== node.nodeValue) node.nodeValue = nextValue;
  });
  root.querySelectorAll?.("[placeholder],[title],[aria-label]").forEach((element) => {
    ["placeholder", "title", "aria-label"].forEach((attribute) => {
      if (element.hasAttribute(attribute)) {
        const current = element.getAttribute(attribute);
        const next = translateValue(current, language);
        if (next !== current) element.setAttribute(attribute, next);
      }
    });
  });
}

export function applyDomLanguage(language) {
  const root = document.getElementById("root");
  if (!root) return () => {};
  document.documentElement.lang = language === "en" ? "en" : "ro";
  let frame = 0;
  let stopped = false;
  const scheduleTranslation = () => {
    if (stopped || frame) return;
    frame = window.requestAnimationFrame(() => {
      frame = 0;
      translateTree(root, language);
    });
  };
  const observer = new MutationObserver(scheduleTranslation);
  observer.observe(root, { childList: true, subtree: true, characterData: true });
  scheduleTranslation();
  return () => {
    stopped = true;
    observer.disconnect();
    if (frame) window.cancelAnimationFrame(frame);
  };
}
